def build_editable_figures(values: dict[str, float]) -> None:
    presentation = Presentation()
    presentation.slide_width = PptxInches(13.333)
    presentation.slide_height = PptxInches(7.5)
    captions = esi.captions(values)
    figures = [
        (f"Figure {index}", name, captions[index - 1])
        for index, name in enumerate(MAIN_FIGURES, start=1)
    ] + [
        (f"Online Resource 1, Fig. S{index}", name, caption)
        for index, (name, caption) in enumerate(ESM_FIGURES, start=1)
    ]
    for label, name, figure_caption in figures:
        slide = presentation.slides.add_slide(presentation.slide_layouts[6])
        title_box = slide.shapes.add_textbox(
            PptxInches(0.5), PptxInches(0.2), PptxInches(12.33), PptxInches(0.55)
        )
        title = title_box.text_frame.paragraphs[0]
        title.text = label
        title.font.name = "Arial"
        title.font.size = PptxPt(22)
        title.font.bold = True
        title.alignment = PP_ALIGN.CENTER
        with PILImage.open(FIGURES / name) as image:
            aspect = image.width / image.height
        width, height = 12.0, 12.0 / aspect
        if height > 5.5:
            height, width = 5.5, 5.5 * aspect
        slide.shapes.add_picture(
            str(FIGURES / name),
            PptxInches((13.333 - width) / 2),
            PptxInches(0.85),
            width=PptxInches(width),
            height=PptxInches(height),
        )
        caption_box = slide.shapes.add_textbox(
            PptxInches(0.6), PptxInches(6.45), PptxInches(12.13), PptxInches(0.9)
        )
        caption_box.text_frame.word_wrap = True
        caption = caption_box.text_frame.paragraphs[0]
        caption.text = figure_caption
        caption.font.name = "Arial"
        caption.font.size = PptxPt(11)
    presentation.save(MANUSCRIPT / "figures.pptx")


