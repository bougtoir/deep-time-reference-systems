def strip_doc_grid(document: Document) -> None:
    """Remove character/line document-grid markup from every section.

    python-docx's default template emits ``w:docGrid w:linePitch=\"360\"`` per
    section. The target journal does not require a document grid, so drop it to
    avoid any character-count-based wrapping interpretation.
    """
    for section in document.sections:
        sect_pr = section._sectPr
        for grid in sect_pr.findall(qn("w:docGrid")):
            sect_pr.remove(grid)


