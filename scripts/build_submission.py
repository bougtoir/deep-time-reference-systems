def build_manuscript(values: dict[str, float]) -> None:
    document = Document()
    style_document(document)
    add_title_page(document)
    abstract = esi.abstract(values)
    captions = esi.captions(values)
    abstract_word_count = len(abstract.split())
    if not 150 <= abstract_word_count <= 250:
        raise ValueError(f"Abstract has {abstract_word_count} words")
    document.add_heading("Abstract", level=1)
    add_rich_paragraph(document, abstract)
    document.add_paragraph("Keywords: " + "; ".join(esi.KEYWORDS))
    body_fragments = []
    for heading, paragraphs in esi.sections(values, *rigidity_grid()):
        document.add_heading(heading, level=1)
        for text in paragraphs:
            figure = re.fullmatch(r"__FIGURE_(\d+)__", text)
            table = re.fullmatch(r"__TABLE_(\d+)__", text)
            if figure:
                add_figure(document, int(figure.group(1)), captions)
            elif table:
                number_ = int(table.group(1))
                name, caption = MAIN_TABLES[number_ - 1]
                add_dataframe_table(document, pd.read_csv(TABLES / name), number_, caption)
            else:
                add_rich_paragraph(document, text)
                body_fragments.append(text)
    document.add_heading("Statements and Declarations", level=1)
    add_declarations(document, level=2)
    document.add_heading("References", level=1)
    for reference in esi.REFERENCES:
        add_reference(document, reference)
    body = "\n".join(body_fragments)
    figure_positions = [body.find(f"Fig. {index}") for index in range(1, len(MAIN_FIGURES) + 1)]
    table_positions = [body.find(f"Table {index}") for index in range(1, len(MAIN_TABLES) + 1)]
    if any(position < 0 for position in figure_positions + table_positions):
        raise ValueError("Every figure and table must be cited in body text")
    if figure_positions != sorted(figure_positions) or table_positions != sorted(table_positions):
        raise ValueError("Figure and table citations must be sequential")
    strip_doc_grid(document)
    document.save(MANUSCRIPT / "manuscript.docx")


