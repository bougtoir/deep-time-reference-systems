def build_manifest_and_zip(files: list[Path]) -> None:
    manifest_path = SUBMISSION_FINAL / "MANIFEST.csv"
    with manifest_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["file", "size_bytes", "sha256"])
        for path in files:
            writer.writerow([path.relative_to(SUBMISSION_FINAL), path.stat().st_size, sha256(path)])
    with zipfile.ZipFile(SUBMISSION_ARCHIVE, "w", compression=zipfile.ZIP_DEFLATED) as handle:
        for path in files + [manifest_path]:
            handle.write(path, path.relative_to(SUBMISSION_FINAL))


